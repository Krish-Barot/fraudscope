// apps/web/hooks/useSocket.ts
// Socket.io client hook — manages WebSocket connection lifecycle
//
// FEATURES:
// - Connects with JWT in handshake auth (token refreshed automatically)
// - Auto-reconnects on disconnect (Socket.io built-in + manual fallback)
// - Type-safe event emitter
// - Exposes connection status for the top bar indicator
// - Cleans up on unmount (prevents memory leaks)
//
// USAGE:
// const { connected, on, off, emit } = useSocket();
//
// useEffect(() => {
//   on('tx:new', handleNewTransaction);
//   emit('subscribe', { channels: ['tx:live'] });
//   return () => off('tx:new', handleNewTransaction);
// }, [on, off, emit]);

'use client';

import { useEffect, useRef, useCallback, useState } from 'react';
import { io, Socket } from 'socket.io-client';
import { useAuth } from '../lib/authContext';

const API_URL = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:3002';

// ─────────────────────────────────────────
// Event type definitions
// Add new event types here as the dashboard grows
// ─────────────────────────────────────────
export interface ServerToClientEvents {
  // New transaction arrived (live feed)
  'tx:new': (data: {
    id: string;
    account_id: string;
    amount: number;
    currency: string;
    merchant_name?: string;
    country_code: string;
    channel?: string;
    status: 'clean' | 'flagged';
    risk_score?: number;
    created_at: string;
  }) => void;

  // New alert generated by rule engine
  'alert:new': (data: {
    id: string;
    transaction_id: string;
    risk_score: number;
    severity: 'low' | 'medium' | 'high' | 'critical';
    status: string;
    triggered_rules: Array<{
      type: string;
      name: string;
      score_contribution: number;
    }>;
    transaction: {
      account_id: string;
      amount: number;
      currency: string;
      country_code: string;
    };
    created_at: string;
  }) => void;

  // Alert status changed by another analyst
  'alert:updated': (data: {
    alert_id: string;
    new_status: string;
    analyst: string;
    action?: string;
    reason?: string;
    updated_at?: string;
    claimed_at?: string;
  }) => void;

  // Alert claimed confirmation
  'alert:claimed': (data: {
    alert_id: string;
    success: boolean;
  }) => void;

  // Rule created, updated, toggled, or deleted
  'rule:updated': (data: {
    action: string;
    ruleId: string;
    timestamp?: string;
  }) => void;

  // Connection confirmation
  'system:connected': (data: {
    userId: string;
    email: string;
    role: string;
    connectedAt: string;
  }) => void;

  // System health metrics (broadcast every 10s)
  'system:status': (data: {
    connected: boolean;
    active_connections: number;
    active_analysts: number;
    timestamp: string;
  }) => void;
}

export interface ClientToServerEvents {
  'subscribe': (data: { channels: string[] }) => void;
  'unsubscribe': (data: { channels: string[] }) => void;
  'alert:claim': (data: { alert_id: string }) => void;
}

export type TypedSocket = Socket<ServerToClientEvents, ClientToServerEvents>;

// ─────────────────────────────────────────
// Hook return type
// ─────────────────────────────────────────
interface UseSocketReturn {
  connected: boolean;
  socket: TypedSocket | null;
  on: <E extends keyof ServerToClientEvents>(
    event: E,
    handler: ServerToClientEvents[E]
  ) => void;
  off: <E extends keyof ServerToClientEvents>(
    event: E,
    handler: ServerToClientEvents[E]
  ) => void;
  emit: <E extends keyof ClientToServerEvents>(
    event: E,
    data: Parameters<ClientToServerEvents[E]>[0]
  ) => void;
}

// ─────────────────────────────────────────
// Singleton socket — shared across all hook instances
// We only want ONE Socket.io connection per browser tab,
// not one per component. The socket is created once and
// reused by all components that call useSocket().
// ─────────────────────────────────────────
let globalSocket: TypedSocket | null = null;
let connectionCount = 0; // tracks how many components are using the socket

export function useSocket(): UseSocketReturn {
  const { accessToken, user } = useAuth();
  const [connected, setConnected] = useState(false);
  const socketRef = useRef<TypedSocket | null>(null);

  // ── Initialize socket connection ────────────────────────────────
  useEffect(() => {
    // Don't connect if not authenticated
    if (!accessToken || !user) {
      return;
    }

    connectionCount++;

    // Reuse existing socket or create new one if not yet created
    if (!globalSocket) {
      globalSocket = io(API_URL, {
        // JWT in handshake auth — sent to server middleware
        auth: { token: accessToken },

        // Transport config
        transports: ['websocket', 'polling'],  // prefer WebSocket, fall back to polling

        // Auto-reconnect settings
        reconnection: true,
        reconnectionAttempts: Infinity,  // keep trying until tab is closed
        reconnectionDelay: 1000,         // start with 1s delay
        reconnectionDelayMax: 10000,     // max 10s between attempts
        randomizationFactor: 0.5,        // add jitter to prevent thundering herd

        // Timeout
        timeout: 10000,
      }) as TypedSocket;
    }

    const socket = globalSocket;
    socketRef.current = socket;
    setConnected(socket.connected);

    // ── Connection events ─────────────────────────────────────────
    const handleConnect = () => {
      console.log('[Socket.io] Connected:', socket.id);
      setConnected(true);
    };

    const handleDisconnect = (reason: string) => {
      console.log('[Socket.io] Disconnected:', reason);
      setConnected(false);

      // If server closed the connection (auth failure, etc.),
      // don't auto-reconnect — user needs to log in again
      if (reason === 'io server disconnect') {
        socket.connect(); // manually reconnect after token refresh
      }
    };

    const handleConnectError = (error: Error) => {
      console.error('[Socket.io] Connection error:', error.message);
      setConnected(false);
    };

    socket.on('connect', handleConnect);
    socket.on('disconnect', handleDisconnect);
    socket.on('connect_error', handleConnectError);

    // If socket is already connected when this component mounts, sync state
    if (socket.connected) {
      setConnected(true);
    }

    // ── Cleanup ───────────────────────────────────────────────────
    return () => {
      connectionCount--;

      socket.off('connect', handleConnect);
      socket.off('disconnect', handleDisconnect);
      socket.off('connect_error', handleConnectError);

      // Only disconnect when NO components are using the socket
      if (connectionCount <= 0) {
        connectionCount = 0;
        globalSocket?.disconnect();
        globalSocket = null;
        socketRef.current = null;
        setConnected(false);
      }
    };
  }, [accessToken, user]);

  // ── Update auth token when it refreshes ────────────────────────
  // When the access token is refreshed (every 14 minutes), update
  // the socket auth so the next reconnection uses the new token
  useEffect(() => {
    if (socketRef.current && accessToken) {
      socketRef.current.auth = { token: accessToken };
    }
  }, [accessToken]);

  // ── Stable event listener methods ──────────────────────────────
  const on = useCallback(<E extends keyof ServerToClientEvents>(
    event: E,
    handler: ServerToClientEvents[E]
  ) => {
    (socketRef.current || globalSocket as any)?.on(event, handler);
  }, []);

  const off = useCallback(<E extends keyof ServerToClientEvents>(
    event: E,
    handler: ServerToClientEvents[E]
  ) => {
    (socketRef.current || globalSocket as any)?.off(event, handler);
  }, []);

  const emit = useCallback(<E extends keyof ClientToServerEvents>(
    event: E,
    data: Parameters<ClientToServerEvents[E]>[0]
  ) => {
    (socketRef.current || globalSocket as any)?.emit(event, data);
  }, []);

  return {
    connected,
    socket: socketRef.current || globalSocket,
    on,
    off,
    emit,
  };
}